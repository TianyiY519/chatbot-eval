"""Apply human review decisions to finished test sets, without regenerating them.

Usage:
    python scripts/07_revise_testset.py                 # applies data/revisions.json to sets A and B
    python scripts/07_revise_testset.py --dry-run       # show what would change

data/revisions.json:
  "replace": {pair_id: reason}   swap in an unused draft that passed every check in 03, from the
                                 same document, on a page no other question in the set uses, and
                                 not similar to any question in either set; only the swap is translated
  "edit":    {pair_id: {...}}    reworded question and/or answer per language (written by a reviewer)

Also adds question_type to every case:
  source_specific  names a report, organisation, year or document symbol
  natural_user     asked the way a user would, without naming the source
Writes data/testset_<SET>.jsonl/.csv and data/testset_<SET>_changes.csv (what changed and why).
"""
import argparse
import csv
import json
import re
from difflib import SequenceMatcher

from llm import ROOT, langchain_chat

SOURCE_HINT = re.compile(r"\b(19|20)\d\d\b|\bA/\d+/\d+\b|Report|Statistics|State of|SOFI|UNICEF|WHO|World Health|"
                         r"UNDP|FAO|Secretary-General|United Nations|UN report", re.I)
SIMILAR = 0.6  # SequenceMatcher ratio above which two questions count as the same topic


def question_type(question: str) -> str:
    return "source_specific" if SOURCE_HINT.search(question) else "natural_user"


def similar(a: str, b: str) -> bool:
    return SequenceMatcher(None, a.lower(), b.lower()).ratio() > SIMILAR


def load(name: str) -> list[dict]:
    """The set as generated by 03 (kept in data/original/ on the first run), so re-running applies revisions once."""
    orig = ROOT / "data" / "original" / f"testset_{name}.jsonl"
    if not orig.exists():
        orig.parent.mkdir(exist_ok=True)
        orig.write_text((ROOT / "data" / f"testset_{name}.jsonl").read_text(encoding="utf-8"), encoding="utf-8")
    return [json.loads(l) for l in orig.open(encoding="utf-8")]


def spares_for(name: str, used_questions: set[str]) -> list[dict]:
    """Drafts that passed every check in 03 but were not used: leftovers of <SET>, then top-ups in <SET>_extra
    (python scripts/02_generate_testset.py --set A_extra --docs ... --page-offset 8, then 03 --keep 0)."""
    spares = []
    extras = sorted(p.name[len("testset_"):-len("_review.csv")]
                    for p in (ROOT / "data").glob(f"testset_{name}_extra*_review.csv"))
    for src in [name, *extras]:
        review = ROOT / "data" / f"testset_{src}_review.csv"
        if not review.exists():
            continue
        ok = {r["raw_id"] for r in csv.DictReader(review.open(encoding="utf-8-sig")) if r["ok"] == "True"}
        raw = [json.loads(l) for l in (ROOT / "data" / f"testset_{src}_raw.jsonl").open(encoding="utf-8")]
        spares += [r for r in raw if r["id"] in ok and r["question"] not in used_questions and len(r["sources"]) == 1]
    return spares


STOP = set("the a an of to in and or for on by with as at from is are was were be that this what how which according "
           "report world does do did its their it into than more most about between under over per percent".split())


def overlap(a: dict, b: dict) -> float:
    """Share of key words in common between two cases (question + answer)."""
    words = lambda c: {w for w in re.findall(r"[a-z]{3,}", (c["question"] + " " + c["reference_answer"]).lower())
                       if w not in STOP}
    wa, wb = words(a), words(b)
    return len(wa & wb) / max(len(wa | wb), 1)


def same_fact(spare: dict, kept: list[dict]) -> bool:
    """A spare from a page that is already used must answer something different: no similar answer, no shared figure."""
    nums = lambda t: {n for n in re.findall(r"\d[\d.]*\d|\d", t.replace(",", "")) if len(n) > 1
                      and not re.fullmatch(r"(19|20)\d\d", n)}  # shared years don't make the same fact
    for k in kept:
        if k["sources"][0] != spare["sources"][0]:
            continue
        if SequenceMatcher(None, k["reference_answer"].lower(), spare["reference_answer"].lower()).ratio() > 0.5 \
                or nums(k["reference_answer"]) & nums(spare["reference_answer"]):
            return True
    return False


def write(name: str, cases: list[dict]) -> None:
    out = ROOT / "data" / f"testset_{name}.jsonl"
    with out.open("w", encoding="utf-8") as f:
        for c in cases:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    with out.with_suffix(".csv").open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["id", "pair_id", "language", "question_type", "question", "reference_answer", "sources"])
        for c in cases:
            w.writerow([c["id"], c["pair_id"], c["language"], c["question_type"], c["question"],
                        c["reference_answer"], " | ".join(c["sources"])])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sets", default="A,B")
    ap.add_argument("--revisions", default=str(ROOT / "data" / "revisions.json"))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--allow-other-doc", action="store_true",
                    help="if a document has no spare left, take one from another document")
    args = ap.parse_args()

    rev = json.load(open(args.revisions, encoding="utf-8"))
    names = [n.strip() for n in args.sets.split(",")]
    sets = {n: load(n) for n in names}
    model = None if args.dry_run else langchain_chat("judge", temperature=0)
    from importlib import import_module
    translate = import_module("03_verify_testset").translate

    for name in names:
        cases = sets[name]
        langs = list(dict.fromkeys(c["language"] for c in cases))
        changes = []
        # questions of *all* sets (minus the ones being replaced) must not resemble a replacement
        replaced = {p for p in rev["replace"] if p.startswith(name)}
        others = [c["question"] for n in names for c in sets[n]
                  if c["language"] == "en" and c["pair_id"] not in replaced]
        kept_en = [c for c in cases if c["language"] == "en" and c["pair_id"] not in replaced]
        all_en = [c for n in names for c in sets[n] if c["language"] == "en" and c["pair_id"] not in rev["replace"]]
        pool = spares_for(name, {c["question"] for c in cases if c["language"] == "en"})

        for pair in sorted(replaced):
            old = next(c for c in cases if c["pair_id"] == pair and c["language"] == "en")
            doc = old["sources"][0].split("#")[0]
            ok = lambda s: (not same_fact(s, kept_en) and not any(similar(s["question"], q) for q in others)
                            and not any(overlap(s, k) > 0.35 for k in all_en))
            pick = next((s for s in pool if s["sources"][0].split("#")[0] == doc and ok(s)), None)
            if pick is None and args.allow_other_doc:  # better than keeping a duplicate
                pick = next((s for s in pool if ok(s)), None)
            if pick is None:
                print(f"{pair}: no suitable spare from {doc}; kept as is (top up with 02 --set {name}_extra)")
                continue
            pool.remove(pick)
            others.append(pick["question"])
            kept_en.append(pick)
            all_en.append(pick)
            print(f"{pair}: replace ({rev['replace'][pair]})\n   old: {old['question'][:110]}\n"
                  f"   new: {pick['question'][:110]}  [{pick['sources'][0]}]")
            if args.dry_run:
                continue
            base = {"pair_id": pair, "reference_contexts": pick["reference_contexts"], "sources": pick["sources"],
                    "synthesizer": pick["synthesizer"]}
            new = []
            for code in langs:
                qa = ({"question": pick["question"], "reference_answer": pick["reference_answer"]} if code == "en"
                      else translate(model, {**pick, "id": pair}, code))
                new.append({"id": f"{pair}-{code}", "language": code, **qa, **base})
            i = next(k for k, c in enumerate(cases) if c["pair_id"] == pair)
            cases[i:i + len(langs)] = new
            changes.append([pair, "replaced", rev["replace"][pair], old["question"], pick["question"]])

        for pair, e in rev["edit"].items():
            if not pair.startswith(name):
                continue
            for c in cases:
                if c["pair_id"] == pair and c["language"] in e:
                    before = c["question"]
                    c.update(e[c["language"]])
                    if c["language"] == "en":
                        changes.append([pair, "edited", e["reason"], before, c["question"]])
            print(f"{pair}: edit ({e['reason']})")

        for c in cases:  # type follows the English wording; reviewer can override in revisions.json
            en_q = next(x["question"] for x in cases if x["pair_id"] == c["pair_id"] and x["language"] == "en")
            c["question_type"] = rev["edit"].get(c["pair_id"], {}).get("question_type") or question_type(en_q)

        if args.dry_run:
            continue
        write(name, cases)
        with (ROOT / "data" / f"testset_{name}_changes.csv").open("w", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f)
            w.writerow(["pair_id", "change", "reason", "before (en)", "after (en)"])
            w.writerows(changes)
        types = [c["question_type"] for c in cases if c["language"] == "en"]
        print(f"set {name}: {len(changes)} changes, {len(types)} questions "
              f"({types.count('source_specific')} source_specific, {types.count('natural_user')} natural_user)\n")


if __name__ == "__main__":
    main()
